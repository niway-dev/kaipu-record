export interface SeedOptions {
  /** The run's start; every `createdAt` is this minus a fixed offset. */
  now: number;
  /**
   * Which items: `demo` (the full set), `empty` (only the workspace identity), `missing` (no
   * folder at all: the workspace reads as not connected, like an unplugged drive).
   */
  content: "demo" | "empty" | "missing";
  /** Add the native-cursor recording (profiles with the cursor flag on). */
  cursorRecording?: boolean;
  /** Add the recording with two overlapping floating images (profiles with `timeline-levels`). */
  floatingImages?: boolean;
  /** Add the screenshot that draws real text (profiles that exercise text recognition). */
  textScreenshot?: boolean;
  /** Add the two screenshots the Colors panel states open (profiles that exercise it). */
  colorsScreenshots?: boolean;
  /**
   * Add the screenshot saved with one locked redaction (`LOCKED_SHOT`), for the image editor's
   * "Permanent" tag. Only the profile that needs it turns it on, so no other state's vault changes.
   */
  lockedRedaction?: boolean;
  /**
   * Add `MOCK_SHOTS`, the screenshots of the image editor's step badge and Redact card states.
   * Only the profile that needs them turns it on, so no other state's vault changes.
   */
  mockShots?: boolean;
  /** Add the P3 swatch sheet and a private copy of “Settings page” (Inspect states C3 and C9). */
  inspectShots?: boolean;
  /**
   * Leave a canvas document that cannot be parsed beside "Settings page" (the image editor's
   * reopen then opens the flat image and says so).
   */
  corruptCanvas?: boolean;
  /**
   * Make "Check and fix files" find something: `fixable`, a recording whose file name does
   * not match its title; `attention`, a recording whose record cannot be read.
   */
  reconcile?: "fixable" | "attention";
  fixturesDir?: string;
}

function tagIdsOf(names: readonly TagName[] = []): { tagIds?: string[]; tagNames?: string[] } {
  if (names.length === 0) return {};
  const tags = names.map((name) => TAGS.find((t) => t.name === name)!);
  return { tagIds: tags.map((t) => t.id), tagNames: tags.map((t) => t.name) };
}

async function writeJson(file: string, value: unknown): Promise<void> {
  await writeFile(file, `${JSON.stringify(value, null, 2)}\n`);
}

/** A cursor that circles the centre of the display, with two clicks: a visible drawn cursor. */
function cursorTrackJson(seconds: number): unknown {
  const t: number[] = [];
  const x: number[] = [];
  const y: number[] = [];
  for (let ms = 0; ms <= seconds * 1000; ms += 50) {
    const angle = (ms / 4000) * 2 * Math.PI;
    t.push(ms);
    x.push(Number((0.5 + 0.18 * Math.cos(angle)).toFixed(4)));
    y.push(Number((0.5 + 0.22 * Math.sin(angle)).toFixed(4)));
  }
  return {
    version: 1,
    display: { id: "1", width: 1920, height: 1080, scaleFactor: 1 },
    anchor: "exact",
    clicksAvailable: true,
    t,
    x,
    y,
    clicks: [
      { t: 2000, x: 0.68, y: 0.5, button: 0 },
      { t: 6000, x: 0.32, y: 0.5, button: 0 },
    ],
  };
}

/** A PNG's pixel size, from its IHDR chunk (bytes 16 to 24). */
function pngSize(file: Buffer): { width: number; height: number } {
  return { width: file.readUInt32BE(16), height: file.readUInt32BE(20) };
}

/**
 * Writes `LOCKED_SHOT`: the flat PNG, its sidecar, and a version 2 canvas document (ADR 0053)
 * with the base asset and one locked SOLID redaction over the middle half of the image. The
 * PNG is the baked result a real save leaves: a grey window-like image whose redacted region
 * is the solid fill, so the "Permanent" tag sits beside an area that really is gone. The
 * document is written by hand, in world px, and pinned by `seed-locked-redaction.test.ts`,
 * which parses it with the editor's own reader.
 */
export async function seedLockedRedactionShot(
  vaultDir: string,
  meta: string,
  fixtures: string,
  now: number,
): Promise<void> {
  // The window fixture gives the size; the pixels are drawn here, with the redaction baked in.
  const { width, height } = pngSize(await readFile(path.join(fixtures, FIXTURE_FILES.screens[3])));
  const region = {
    x: Math.round(width / 4),
    y: Math.round(height / 4),
    w: Math.round(width / 2),
    h: Math.round(height / 2),
  };
  const png = paintPng(
    width,
    height,
    [70, 72, 80],
    [
      [0, 0, width, Math.round(height / 12), [52, 54, 60]],
      [region.x, region.y, region.w, region.h, REDACTION_SOLID_RGB],
    ],
  );
  await writeFile(path.join(vaultDir, `${LOCKED_SHOT.stem}.png`), png);
  await writeJson(path.join(meta, `${LOCKED_SHOT.stem}.json`), {
    sidecarVersion: 2,
    assetId: ASSETS.lockedShot,
    title: LOCKED_SHOT.title,
    createdAt: now - LOCKED_SHOT.ago,
  });
  const assets = path.join(meta, `${LOCKED_SHOT.stem}.assets`);
  await mkdir(assets, { recursive: true });
  await writeFile(path.join(assets, "base.png"), png);
  await writeJson(path.join(meta, `${LOCKED_SHOT.stem}.canvas.json`), {
    schemaVersion: 2,
    items: [
      {
        id: "image-base",
        kind: "image",
        assetId: "base",
        x: 0,
        y: 0,
        w: width,
        h: height,
        pixelWidth: width,
        pixelHeight: height,
      },
      {
        id: "a1",
        kind: "blur",
        ...region,
        style: "solid",
        locked: true,
        lockedAt: now - LOCKED_SHOT.savedAgo,
      },
    ],
    frame: { bg: "none", padding: 0, radius: 0, shadow: 0 },
  });
}

async function seedRecording(
  vaultDir: string,
  meta: string,
  fixtures: string,
  now: number,
  item: RecordingFixture,
): Promise<void> {
  const media = path.join(vaultDir, `${item.stem}.mp4`);
  await copyFile(path.join(fixtures, FIXTURE_FILES.cut(item.cut)), media);
  await copyFile(path.join(fixtures, FIXTURE_FILES.thumbnail), path.join(meta, `${item.stem}.jpg`));
  const createdAt = now - item.ago;
  await writeJson(path.join(meta, `${item.stem}.json`), {
    sidecarVersion: 2,
    assetId: item.assetId,
    title: item.title,
    durationSeconds: item.cut,
    createdAt,
    ...(item.derivedFrom ? { derivedFromAssetId: item.derivedFrom } : {}),
    ...(item.exportPreset ? { exportPreset: item.exportPreset } : {}),
    ...tagIdsOf(item.tags),
    capture: {
      mode: "screen",
      cursorPixels: item.cursorTrack ? "excluded" : "embedded",
      width: 1920,
      height: 1080,
      ratio: null,
    },
    ...(item.webcam
      ? {
          webcam: {
            startOffsetMs: 0,
            offsetQuality: "exact",
            width: 640,
            height: 480,
            fps: 30,
          },
        }
      : {}),
  });
  if (item.webcam) {
    await copyFile(
      path.join(fixtures, FIXTURE_FILES.webcam),
      path.join(meta, `${item.stem}.webcam.mp4`),
    );
  }
  if (item.cursorTrack) {
    await writeJson(path.join(meta, `${item.stem}.cursor.json`), cursorTrackJson(item.cut));
  }
  if (item.floating) {
    const { back, front } = FLOATING_IMAGES;
    const assets = path.join(meta, `${item.stem}.assets`);
    await mkdir(assets, { recursive: true });
    await writeFile(
      path.join(assets, `${back.assetId}.png`),
      paintPng(
        back.width,
        back.height,
        [40, 90, 160],
        [
          [0, 0, back.width, 120, [30, 60, 110]],
          [160, 300, 1280, 90, [90, 140, 210]],
          [160, 450, 900, 90, [90, 140, 210]],
        ],
      ),
    );
    await writeFile(
      path.join(assets, `${front.assetId}.png`),
      paintPng(
        front.width,
        front.height,
        [220, 120, 40],
        [
          [80, 80, 640, 120, [250, 190, 120]],
          [80, 300, 640, 420, [180, 90, 20]],
        ],
      ),
    );
    await writeJson(path.join(meta, `${item.stem}.edit.json`), {
      version: 1,
      scene: floatingScene(item.cut),
    });
    const source = await stat(media);
    await writeJson(path.join(meta, `${item.stem}.edit.meta.json`), {
      sourceSizeBytes: source.size,
      sourceMtimeMs: source.mtimeMs,
      assetIds: [back.assetId, front.assetId],
      savedAt: createdAt + HOUR,
      exportedSavedAt: null,
    });
  }
  if (item.edited) {
    const savedAt = createdAt + HOUR;
    await writeJson(path.join(meta, `${item.stem}.edit.json`), {
      version: 1,
      scene: {
        items: [{ id: "clip-1", kind: "clip", sourceStart: 0, sourceEnd: item.cut }],
        // A box over the first six seconds and a blur from 1 s to 4 s: the editor's annotation
        // and privacy lanes have content to select.
        overlays: [
          {
            id: "box-1",
            kind: "box",
            start: 0.5,
            end: 6,
            color: "#ff3b6b",
            x: 0.12,
            y: 0.18,
            w: 0.3,
            h: 0.22,
            stroke: 3,
            seed: 7,
          },
        ],
        zoomSegments: [
          {
            id: "zoom-1",
            start: 2,
            end: 5,
            scale: 2,
            smoothing: 70,
            mode: "fixed",
            origin: "manual",
            trigger: null,
            anchor: { x: 0.5, y: 0.5 },
          },
        ],
        redactions: [
          {
            id: "blur-1",
            kind: "blur",
            start: 1,
            end: 4,
            rect: { x: 0.55, y: 0.55, w: 0.3, h: 0.2 },
            intensity: 70,
            style: "gaussian",
          },
        ],
        zoomSensitivity: 55,
        audioMuted: false,
        mutedRanges: [{ id: "mute-1", sourceStart: 6, sourceEnd: 7.5 }],
        webcam: null,
      },
    });
    const source = await stat(media);
    await writeJson(path.join(meta, `${item.stem}.edit.meta.json`), {
      sourceSizeBytes: source.size,
      sourceMtimeMs: source.mtimeMs,
      assetIds: [],
      savedAt,
      exportedSavedAt: null,
    });
  }
}

/** Build the catalog's workspace in `vaultDir` (an empty, throwaway folder). */
export async function seedCatalogVault(vaultDir: string, options: SeedOptions): Promise<void> {
  const { now } = options;
  if (options.content === "missing") {
    await rm(vaultDir, { recursive: true, force: true });
    return;
  }
  const fixtures = options.fixturesDir ?? FIXTURES_DIR;
  const meta = path.join(vaultDir, ".kaipu");
  await mkdir(path.join(meta, "workspace"), { recursive: true });
  // The registry adopts this identity on first launch, so the app calls the folder by this
  // name instead of the folder's random temp name or "Default workspace".
  await writeJson(path.join(meta, "workspace", "identity.json"), {
    version: 1,
    id: WORKSPACE_ID,
    name: WORKSPACE_NAME,
    color: "lagoon",
    initials: "DW",
    createdAt: now - 30 * DAY,
  });
  if (options.content === "empty") return;

  await writeJson(path.join(meta, "tags.json"), {
    version: 1,
    tags: TAGS.map((tag, index) => ({
      id: tag.id,
      name: tag.name,
      slug: tag.name.toLowerCase(),
      color: tag.color,
      createdAt: now - (20 - index) * DAY,
      updatedAt: now - (20 - index) * DAY,
      createdOn: DEVICE_ID,
      updatedOn: DEVICE_ID,
      deletedAt: null,
    })),
  });

  const recordings = [
    ...(options.floatingImages ? [FLOATING_RECORDING] : []),
    ...(options.cursorRecording ? [CURSOR_RECORDING] : []),
    ...RECORDINGS,
  ];
  for (const item of recordings) await seedRecording(vaultDir, meta, fixtures, now, item);

  for (const shot of SCREENSHOTS) {
    await copyFile(
      path.join(fixtures, FIXTURE_FILES.screens[shot.file]),
      path.join(vaultDir, `${shot.stem}.png`),
    );
    await writeJson(path.join(meta, `${shot.stem}.json`), {
      sidecarVersion: 2,
      assetId: shot.assetId,
      title: shot.title,
      createdAt: now - shot.ago,
      ...tagIdsOf("tags" in shot ? shot.tags : []),
    });
  }

  if (options.corruptCanvas) {
    await writeFile(path.join(meta, `${SCREENSHOTS[0].stem}.canvas.json`), "{ not json\n");
  }

  if (options.textScreenshot) {
    await copyFile(TEXT_FIXTURE, path.join(vaultDir, `${TEXT_SHOT.stem}.png`));
    await writeJson(path.join(meta, `${TEXT_SHOT.stem}.json`), {
      sidecarVersion: 2,
      assetId: ASSETS.textShot,
      title: TEXT_SHOT.title,
      createdAt: now - TEXT_SHOT.ago,
    });
  }

  if (options.colorsScreenshots) {
    const extras = [
      {
        file: FIXTURE_FILES.colorsShot,
        assetId: ASSETS.colorsShot,
        stem: ITEM_IDS.colorsShot,
        ago: 5 * HOUR,
      },
      {
        file: FIXTURE_FILES.photoShot,
        assetId: ASSETS.photoShot,
        stem: ITEM_IDS.photoShot,
        ago: 7 * HOUR,
      },
    ];
    for (const shot of extras) {
      await copyFile(path.join(fixtures, shot.file), path.join(vaultDir, `${shot.stem}.png`));
      await writeJson(path.join(meta, `${shot.stem}.json`), {
        sidecarVersion: 2,
        assetId: shot.assetId,
        title: shot.stem,
        createdAt: now - shot.ago,
      });
    }
  }

  if (options.mockShots) {
    for (const shot of MOCK_SHOTS) {
      const target = path.join(vaultDir, `${shot.stem}.png`);
      if (shot.source === "settings") {
        await copyFile(path.join(fixtures, FIXTURE_FILES.screens[0]), target);
      } else {
        await writeFile(target, shot.source === "sizes" ? stepSizesPng() : redactionPng());
      }
      await writeJson(path.join(meta, `${shot.stem}.json`), {
        sidecarVersion: 2,
        assetId: shot.assetId,
        title: shot.stem,
        createdAt: now - shot.ago,
      });
    }
  }

  if (options.lockedRedaction) await seedLockedRedactionShot(vaultDir, meta, fixtures, now);

  if (options.inspectShots) {
    await copyFile(P3_FIXTURE, path.join(vaultDir, `${P3_SHOT.stem}.png`));
    await writeJson(path.join(meta, `${P3_SHOT.stem}.json`), {
      sidecarVersion: 2,
      assetId: ASSETS.p3Shot,
      title: P3_SHOT.title,
      createdAt: now - P3_SHOT.ago,
    });
    await copyFile(
      path.join(fixtures, FIXTURE_FILES.screens[0]),
      path.join(vaultDir, `${PINS_SHOT.stem}.png`),
    );
    await writeJson(path.join(meta, `${PINS_SHOT.stem}.json`), {
      sidecarVersion: 2,
      assetId: ASSETS.pinsShot,
      title: PINS_SHOT.title,
      createdAt: now - PINS_SHOT.ago,
    });
  }

  if (options.reconcile === "fixable") {
    await copyFile(path.join(fixtures, FIXTURE_FILES.cut(4)), path.join(vaultDir, "clip-0001.mp4"));
    await writeJson(path.join(meta, "clip-0001.json"), {
      sidecarVersion: 2,
      assetId: "c0a1a10c-0000-4000-8000-000000000301",
      title: "Planning call",
      durationSeconds: 4,
      createdAt: now - 12 * DAY,
    });
  } else if (options.reconcile === "attention") {
    await copyFile(
      path.join(fixtures, FIXTURE_FILES.cut(4)),
      path.join(vaultDir, "Planning call.mp4"),
    );
    await writeFile(path.join(meta, "Planning call.json"), "{ not json\n");
  }

  await copyFile(path.join(fixtures, FIXTURE_FILES.gif), path.join(vaultDir, "Loop preview.gif"));
  await copyFile(path.join(fixtures, FIXTURE_FILES.thumbnail), path.join(meta, "Loop preview.jpg"));
  await writeJson(path.join(meta, "Loop preview.json"), {
    sidecarVersion: 2,
    assetId: ASSETS.loopGif,
    title: "Loop preview",
    durationSeconds: 4,
    createdAt: now - 10 * DAY,
    derivedFromAssetId: ASSETS.lightCopy,
    gifWidth: 480,
    gifHeight: 270,
    gifFps: 10,
  });
}
